"""คำนวณ transform ที่ทำให้ชิ้นในซีนปกติ "เคลื่อนและหมุน" ไปเป็นตำแหน่งของซีนเมนู

    python figma-scene.py   →  figma-scene.css

แนวคิด (เจ้าของงานยืนยัน 2026-08-04):
  **ทุกชิ้นเป็นชิ้นเดียวกัน ไม่ได้สลับหน้า** — พอดึงเชือก ฟอร์ม/การ์ด/ปากกา
  จะ "หมุนและเคลื่อน" ไปยังจุดที่ดีไซน์กำหนดไว้ในซีนเมนู
  → หน้าเว็บต้องมีชิ้นชุดเดียว แล้วเปลี่ยน transform เอา ห้ามทำสำเนาสองชุด
  → เฟส 3 แค่เติม transition ให้ transform ตัวเดิม ก็ได้อนิเมชันทันที

ตรวจแล้วว่าเป็นการย้าย+หมุนล้วน: ขนาดก่อนหมุนของทุกชิ้นเท่ากันทั้งสองซีน
(ต่างกันไม่เกิน 0.3px = การปัดเศษ) จึงไม่ต้องมี scale

พิกัดที่ใช้เป็น absoluteBoundingBox = **กล่องหลังหมุนแล้ว** (figma-layout-spec ข้อ 2)
→ จุดกึ่งกลางของกล่องหลังหมุน = จุดกึ่งกลางจริงของชิ้น ใช้เป็นแกนหมุนได้เลย

⚠ องศาใน Figma เครื่องหมายกลับด้านกับ CSS → มุมที่ต้องหมุนเพิ่ม = mainRot - menuRot
   (ตรวจแล้วกับฟอร์ม: จุดข้อความ 1164.45,205.923 ในซีนปกติ
    หมุน 11° รอบ 1395.25,420.5 แล้วเลื่อน +108.2 ได้ 1317.83,165.83
    ตรงกับค่าจริงในไฟล์ซีนเมนู 1317.8,165.823)
"""
import math
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
ROOT = Path(__file__).resolve().parent

# ค่าที่วัดจากไฟล์ export จริง (รอบ 2026-08-04 ใน images/edit main figma/)
# วิธีวัด: สุ่มจุดตามเส้น <path> ของชิ้นเดียวกันในสองซีน แล้ว fit similarity transform
#   - จุดบนเส้นเป็นพิกัดจริงทางเรขาคณิต หมุนตามชิ้นเสมอ ต่างจากกล่องครอบที่ไม่หมุนตาม
#   - ตรวจแล้วทุกชิ้นได้ scale = 1.0000 => ขยับกับหมุนล้วน ไม่มีการย่อ
#   - ชิ้นที่เทียบเส้นไม่ได้ (รูปล้วน) ใช้ผลต่างของกล่องครอบแทน เพราะไม่หมุนอยู่แล้ว
#
# ชื่อ CSS, ชื่อเลเยอร์ใน Figma, องศาที่ต้องหมุนเพิ่ม, (dx, dy), จุดหมุน (กึ่งกลางกล่องซีนปกติ)
PIECES = [
    ("#pcCloud1", "clound1", 0, (67, 155), None),
    ("#pcBg2", "bg2", 0, (127, 0), None),
    ("#pcBg1", "bg1", 0, (191, 12), None),
    ("#pcSpin", "bg-spin", 0, (35.07, 0), None),
    ("#pcDotRing", "Rectangle 34", 0, (718, 253), None),
    ("#pcStarDrop", "animate star drop", 0, (171.77, 0), None),
    ("#pcForm", "form card", 11.00, (108.02, 0), (1395.37, 421.22)),
    # ⚠ สำรับการ์ด 3 ใบไม่อยู่ในนี้แล้ว — ตำแหน่งซีนเมนูของมันอยู่ใน figma-anim.css
    #   เพราะแต่ละ "ช่อง" ในสำรับมีตำแหน่งซีนเมนูคนละค่า (image3 A กับ image3 B)
    #   และการ์ดสลับช่องกันตลอด จะผูก transform รายชิ้นแบบชิ้นอื่นไม่ได้
    #   ค่าที่ใช้แปลงไปแล้วอยู่ที่นั่น: ช่อง 2 = 19.76° (140.5,-82.8) · ช่อง 1 = 54.17° (145.3,-305.6)
    ("#pcCardC", "image3 C", 26.03, (88.94, 0), (1806.86, 415.50)),
    ("#pcCardD", "image3 D", 13.06, (29.68, 41.84), (1942.15, 509.30)),
    ("#pcStampInk", "stampink", 0, (56, 0), None),
    ("#pcStampStick", "stampstick", 0, (56, 0), None),
    ("#pcPen", "pen", 60.35, (-112.43, -24.47), (1593.59, 434.87)),
    ("#pcAdmin", "admin", 0, (56, 0), None),
    # ⚠ ตัวเดียวที่ค่า "ไม่ได้มาจากการวัด" — เจ้าของงานสั่งแก้ 2026-08-18
    #   Group 23 คือ "รอยตรา" ที่ปั๊มอยู่บนกระดาษฟอร์ม (ไม่ใช่ด้ามตรา/กล่องหมึก
    #   ที่วางอยู่บนโต๊ะแยกต่างหาก) วัดจากไฟล์ export ได้ 0,0 ทั้งสองซีน
    #   = ในไฟล์ Figma ซีนเมนู ฟอร์มถูกย้ายไปแต่รอยตราถูกทิ้งไว้ที่เดิม
    #   ของจริงรอยตราต้องติดไปกับกระดาษ → ใช้ค่าชุดเดียวกับ form card เป๊ะ
    #   (แกนหมุนเดียวกัน+องศาเดียวกัน = ขยับแข็งไปด้วยกัน ไม่เพี้ยนตำแหน่งบนกระดาษ)
    ("#pcSeal", "Group 23", 11.00, (108.02, 0), (1395.37, 421.22)),
]

# ชิ้นที่อยู่นิ่งทั้งสองซีน — วัดแล้วได้ 0,0 ทุกตัว เขียนไว้เป็นหลักฐานว่าไม่ได้ลืม
STILL = ["clound2", "bg star line", "background Star", "rope"]


def g(n):
    return f"{round(n, 2):g}"


def main():
    out = ["""/* ============================================================
   ซีนเมนู — ชิ้นเดิมเคลื่อนและหมุนไปที่ใหม่
   สร้างด้วย figma-scene.py ห้ามแก้ด้วยมือ

   **ไม่ใช่การสลับไปหน้าอื่น** ทุกชิ้นเป็นชิ้นเดียวกันกับซีนปกติ
   พอดึงเชือกก็หมุน+เคลื่อนไปจุดที่ดีไซน์กำหนดไว้ (เฟส 3 ค่อยเติม transition)

   แกนหมุน = จุดกึ่งกลางของชิ้นในซีนปกติ · องศา = ผลต่างของสองซีน
   ============================================================ */
"""]
    for sel, name, drot, (dx, dy), origin in PIECES:
        parts = []
        if abs(dx) > 0.01 or abs(dy) > 0.01:
            parts.append(f"translate({g(dx)}px, {g(dy)}px)")
        if abs(drot) > 0.01:
            parts.append(f"rotate({g(drot)}deg)")
        if not parts:
            continue
        out.append(f"\n/* {name}"
                   f"{'  หมุน ' + g(drot) + ' องศา รอบ ' + g(origin[0]) + ',' + g(origin[1]) if origin else ''} */")
        out.append(f".stage[data-scene='menu'] {sel} {{")
        if origin and abs(drot) > 0.01:
            out.append(f"    transform-origin: {g(origin[0])}px {g(origin[1])}px;")
        out.append(f"    transform: {' '.join(parts)};")
        out.append("}")

    out.append("\n/* อยู่นิ่งทั้งสองซีน ไม่ต้องมีกฎ: " + " · ".join(STILL) + " */")
    (ROOT / "figma-scene.css").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("เขียน figma-scene.css")
    for sel, name, drot, (dx, dy), origin in PIECES:
        print(f"  {name:<20} เลื่อน {dx:+8.2f},{dy:+8.2f}   หมุน {drot:+6.2f} องศา")


if __name__ == "__main__":
    main()
